-- ── Справочник русских блюд: ранжирование и нормализация поиска ─────────────
--
-- 0006 добавила 5432 готовых блюда FNDDS. Povarenok добавляет ещё 131 960
-- позиций, и это меняет не объём, а задачу. Пока блюд было пять тысяч, поиск
-- решал «найти совпадение». На ста тридцати тысячах он решает «выбрать три из
-- сотни одинаково похожих»: по запросу «пирог» триграммное сходство почти
-- одинаково у восьми тысяч позиций, и без внешнего сигнала выдача становится
-- случайной.
--
-- Сигнал берём из самого дампа: сколько рецептов свелось в позицию и сколько у
-- них суммарно просмотров. Это прямая мера того, насколько название расхожее, а
-- расхожее название и есть правильный ответ на вопрос «что ты сфотографировал».
--
-- Миграция идемпотентна: npx tsx scripts/apply-migrations.ts --only 0008

-- ── Сигналы ранжирования ────────────────────────────────────────────────────
alter table ingredients
  add column if not exists popularity_views bigint not null default 0;

alter table ingredients
  add column if not exists source_recipes int not null default 0;

-- Заготовки, соусы, украшения, «Приготовление молочных продуктов» — 5815
-- позиций, которые пользователь не фотографирует как блюдо. Не удаляем: соус
-- может быть и самостоятельным ответом. Понижаем в ранжировании.
alter table ingredients
  add column if not exists is_service boolean not null default false;

create index if not exists ingredients_dish_rank_idx
  on ingredients (kind, popularity_views desc)
  where is_active;

-- ── Нормализация «ё» ────────────────────────────────────────────────────────
--
-- В справочнике «мёд», «свёкла», «гречневая» — через «ё». Пользователь и
-- Povarenok пишут «мед», «свекла». Триграммы это не переживают: замерено на
-- живой базе — запрос «Мед» не возвращает ничего, «мёд» возвращает позицию 2748.
--
-- `search_ingredients` из 0007 намеренно НЕ трогаем. На ней стоит маппинг
-- распознанных ингредиентов, а на нём — H1 и H2; смена правил сравнения сдвинула
-- бы уже собранные метрики, и сравнивать новые данные со старыми стало бы
-- нельзя. Нормализация вводится здесь как отдельная функция и отдельный индекс,
-- ими пользуется только поиск блюд (`search_dishes`, миграция 0009).
--
-- То, что старый поиск не находит «мед» и «свеклу», — настоящий дефект, но
-- чинить его надо осознанно и с перезамером, а не заодно с импортом.
create or replace function public.ru_norm(value text)
returns text
language sql
immutable
strict
parallel safe
as $$
  select regexp_replace(replace(lower(value), 'ё', 'е'), '[^\w\s]', ' ', 'g')
$$;

create index if not exists ingredients_name_ru_norm_trgm_idx
  on ingredients using gin (public.ru_norm(name_ru) gin_trgm_ops);
