-- ── Откуда взялся типовой вес порции ────────────────────────────────────────
--
-- У блюд Povarenok три порции (S/M/L), но получены они по-разному, и это
-- различие обязано быть видно в аналитике:
--
--   1 — квантили p25/p50/p75 самой группы рецептов (458 блюд из 122 607);
--   2 — медиана группы, а S и L от категорийных коэффициентов (73 503);
--   3 — всё от категории, своих данных о порции нет (48 646).
--
-- H8 сравнивает типовой вес из справочника с модельной оценкой массы. Если
-- смешать три уровня, метрика измерит качество категорийного приора, а не
-- справочника: блюд уровня 1 меньше половины процента. Срез по уровню — не
-- украшение отчёта, а условие, при котором гипотеза вообще проверяема.
--
-- Колонка на `ingredients`, а не на `ingredient_portions`: уровень один на
-- блюдо, все три его порции получены одним и тем же способом.
--
-- Миграция идемпотентна: npx tsx scripts/apply-migrations.ts --only 0010

alter table ingredients
  add column if not exists portion_source_level int;

create index if not exists ingredients_portion_level_idx
  on ingredients (portion_source_level)
  where portion_source_level is not null;
