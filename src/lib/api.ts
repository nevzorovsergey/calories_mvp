/**
 * Запросы из браузера к нашим же маршрутам.
 *
 * Единственное, что здесь добавляется к обычному fetch, — потолок ожидания.
 * Он нужен не от медленного сервера, а от молчащего: запрос без потолка
 * остаётся в состоянии pending бесконечно, и экран, который его ждёт, тоже
 * висит навсегда — без ошибки, без повтора и без единого способа понять, что
 * ответа уже не будет.
 *
 * Пятнадцать секунд, а не пять: потолок должен срабатывать только на молчание,
 * и запас здесь важнее скорости реакции. Обычный ответ укладывается в доли
 * секунды, но первое обращение к маршруту бывает дорогим — в dev его собирает
 * turbopack (замерено 6.8 с), на Vercel просыпается холодная функция. Тугой
 * потолок превращал это в «ничего не нашли» на пустом месте.
 */
const TIMEOUT_MS = 15_000;

/** Обычный fetch с потолком; на обрыве отклоняется, как и при офлайне. */
export function apiFetch(path: string, init?: RequestInit): Promise<Response> {
  return fetch(path, { ...init, signal: AbortSignal.timeout(TIMEOUT_MS) });
}

/** POST с телом-JSON: этих трёх строк иначе набирается по копии на вызов. */
export function apiPost(path: string, body: unknown): Promise<Response> {
  return apiFetch(path, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(body),
  });
}
